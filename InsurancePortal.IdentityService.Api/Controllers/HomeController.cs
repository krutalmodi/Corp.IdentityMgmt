using InsurancePortal.IdentityService.Application.DTOs;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using System.Security.Claims;

namespace InsurancePortal.IdentityService.Api.Controllers
{
    /// <summary>
    /// Home controller for checking user authentication
    /// </summary>
    [Route("api/home")]
    [ApiController]
    public class HomeController : ControllerBase
    {
        /// <summary>
        /// Index method - requires Bearer token authentication
        /// </summary>
        /// <remarks>
        /// Only authorized users with a valid Bearer token can access this method.
        /// The email is extracted from the JWT token claims generated by JwtTokenService.
        /// Example header: Authorization: Bearer {your_jwt_token}
        /// </remarks>
        /// <returns>A welcome message with authenticated user information</returns>
        [HttpGet("index")]
        [Authorize(AuthenticationSchemes = "Bearer")]
        public IActionResult Index()
        {
            // Get the email from JWT claims (generated by JwtTokenService)
            // Since [Authorize] ensures only authenticated users reach this method,
            // the email claim will always be present
            var userEmail = User.FindFirstValue(ClaimTypes.Email)
                         ?? User.FindFirst(c => c.Type == ClaimTypes.Email || c.Type.EndsWith("/email") || c.Type == "email")?.Value;
            
            var response = new AuthenticatedUserResponseDto(
                Message: "Welcome to Insurance Portal",
                AuthenticatedUser: userEmail,
                Timestamp: DateTime.UtcNow,
                Description: "This endpoint is only accessible with a valid Bearer token"
            );

            return Ok(response);
        }
    }
}
